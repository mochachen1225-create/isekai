export function maiText(text, gender, ruler = 'demon') {
  const R = RULERS[ruler] || RULERS.demon;
  return String(text)
    .replace(/\{(王講話|王登場|王台詞|王真心話1|王真心話2|王真心話3|尾聲|危機|王)\}/g, (_, k) => R[k])
    .replace(/\{他\}/g, gender === 'm' ? '她' : '他').replace(/\{帥\}/g, gender === 'm' ? '大美女' : '大帥哥');
}

